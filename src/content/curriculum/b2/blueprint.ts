type Seed = {
  id: string;
  number: number;
  moduleId: string;
  title: string;
  goal: string;
  prerequisites: readonly string[];
  previousKnowledge: readonly string[];
  themes: readonly string[];
  grammar: readonly string[];
  discourse: readonly string[];
  dialogueScenario: string;
  readingScenario: string;
  listening: string;
  reading: string;
  writing: string;
  speaking: string;
  review: readonly string[];
  performance: string;
  minutes?: number;
};

function lesson(seed: Seed): B2LessonBlueprint {
  return {
    id: seed.id,
    number: seed.number,
    moduleId: seed.moduleId,
    title: seed.title,
    communicativeGoal: seed.goal,
    previousKnowledge: seed.previousKnowledge,
    prerequisites: seed.prerequisites,
    vocabulary: { themes: seed.themes, newItems: { min: 8, max: 8 } },
    grammar: seed.grammar,
    discourse: seed.discourse,
    dialogueScenario: seed.dialogueScenario,
    readingScenario: seed.readingScenario,
    listeningObjective: seed.listening,
    readingObjective: seed.reading,
    writingObjective: seed.writing,
    speakingObjective: seed.speaking,
    exerciseTypes: CORE,
    reviewDependencies: seed.review,
    assessment: { automaticItems: 10, minCorrect: 8, performance: seed.performance },
    estimatedMinutes: seed.minutes ?? 75,
    distributedReviewMinutes: 30,
    review: IN_REVIEW,
  };
}

