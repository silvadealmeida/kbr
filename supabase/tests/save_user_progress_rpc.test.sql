-- Testes pgTAP do RPC CAS da Fase 4D.2.
-- Execute com `supabase test db` ou, sem CLI, com o script local em
-- `supabase/tests/run-local-sql-tests.sh`.

begin;
select plan(22);

insert into auth.users (id, email)
values
  ('11111111-1111-1111-1111-111111111111', 'owner@example.com'),
  ('22222222-2222-2222-2222-222222222222', 'other@example.com');

-- Token da primeira escrita, para testar replay e token obsoleto.
create temporary table saved_token (token uuid, updated_at timestamptz);
grant all on saved_token to authenticated;

select ok(
  has_function_privilege(
    'authenticated',
    'public.save_user_progress(uuid, uuid, jsonb)',
    'execute'
  ),
  'authenticated can execute the CAS RPC'
);

select ok(
  not has_function_privilege(
    'anon',
    'public.save_user_progress(uuid, uuid, jsonb)',
    'execute'
  ),
  'anonymous cannot execute the CAS RPC'
);

select ok(
  not (select prosecdef from pg_proc where oid = 'public.save_user_progress(uuid, uuid, jsonb)'::regprocedure),
  'RPC is SECURITY INVOKER'
);

select ok(
  (select proconfig from pg_proc where oid = 'public.save_user_progress(uuid, uuid, jsonb)'::regprocedure)
    @> array['search_path=""'],
  'RPC has an empty search_path'
);

set local role anon;
select throws_ok(
  $$select * from public.save_user_progress(
      '11111111-1111-1111-1111-111111111111',
      null,
      '{"v":1,"lessons":{},"cards":{},"history":[],"streak":0,"dailyGoal":10,"lastActive":"2026-11-10T12:00:00.000Z"}'::jsonb
    )$$,
  '42501',
  null,
  'anonymous users cannot execute the RPC'
);

set local role authenticated;
set local request.jwt.claim.sub = '11111111-1111-1111-1111-111111111111';

select results_eq(
  $$select applied, current_sync_id is not null
      from public.save_user_progress(
        '11111111-1111-1111-1111-111111111111',
        null,
        '{"v":1,"lessons":{},"cards":{},"history":[],"streak":0,"dailyGoal":10,"lastActive":"2026-11-10T12:00:00.000Z"}'::jsonb
      )$$,
  $$values (true, true)$$,
  'first write with a null token applies and returns a new sync_id'
);

insert into saved_token
select sync_id, updated_at
  from public.user_progress
 where user_id = '11111111-1111-1111-1111-111111111111';

select results_eq(
  $$select applied
      from public.save_user_progress(
        '11111111-1111-1111-1111-111111111111',
        (select token from saved_token),
        '{"v":1,"lessons":{},"cards":{},"history":[],"streak":2,"dailyGoal":10,"lastActive":"2026-11-10T12:01:00.000Z"}'::jsonb
      )$$,
  $$values (true)$$,
  'the current token applies the next snapshot'
);

select results_eq(
  $$select applied, progress ->> 'streak'
      from public.save_user_progress(
        '11111111-1111-1111-1111-111111111111',
        (select token from saved_token),
        '{"v":1,"lessons":{},"cards":{},"history":[],"streak":9,"dailyGoal":10,"lastActive":"2026-11-10T12:02:00.000Z"}'::jsonb
      )$$,
  $$values (false, '2')$$,
  'replaying an old token returns a conflict with the winning snapshot'
);

select is(
  (select progress ->> 'streak' from public.user_progress
    where user_id = '11111111-1111-1111-1111-111111111111'),
  '2',
  'a stale token does not mutate the row'
);

select results_eq(
  $$select applied, progress ->> 'streak'
      from public.save_user_progress(
        '11111111-1111-1111-1111-111111111111',
        (select sync_id from public.user_progress
          where user_id = '11111111-1111-1111-1111-111111111111'),
        '{"v":1,"lessons":{},"cards":{},"history":[],"streak":3,"dailyGoal":10,"lastActive":"2026-11-10T12:03:00.000Z"}'::jsonb
      )$$,
  $$values (true, '3')$$,
  'the current token applies and returns the new snapshot'
);

select isnt(
  (select sync_id from public.user_progress
    where user_id = '11111111-1111-1111-1111-111111111111'),
  (select token from saved_token),
  'a successful write rotates the sync_id'
);

select isnt(
  (select updated_at from public.user_progress
    where user_id = '11111111-1111-1111-1111-111111111111'),
  null,
  'updated_at is generated by the server'
);

select throws_ok(
  $$select * from public.save_user_progress(
      '22222222-2222-2222-2222-222222222222',
      null,
      '{"v":1,"lessons":{},"cards":{},"history":[],"streak":0,"dailyGoal":10,"lastActive":"2026-11-10T12:00:00.000Z"}'::jsonb
    )$$,
  '42501',
  null,
  'RPC rejects a store built for another user'
);

select throws_ok(
  $$select * from public.save_user_progress(
      '11111111-1111-1111-1111-111111111111',
      null,
      '{"v":1}'::jsonb
    )$$,
  '22023',
  null,
  'RPC rejects an invalid Progress v1 envelope'
);

set local request.jwt.claim.sub = '22222222-2222-2222-2222-222222222222';

select is_empty(
  $$select * from public.user_progress$$,
  'another user reads no progress'
);

select throws_ok(
  $$insert into public.user_progress (user_id, progress, sync_id)
    values (
      '11111111-1111-1111-1111-111111111111',
      '{"v":1,"lessons":{},"cards":{},"history":[],"streak":0,"dailyGoal":10,"lastActive":"2026-11-10T12:00:00.000Z"}'::jsonb,
      gen_random_uuid()
    )$$,
  '42501',
  null,
  'direct table insert for the owner is denied by RLS'
);

select throws_ok(
  $$select * from public.save_user_progress(
      '11111111-1111-1111-1111-111111111111',
      null,
      '{"v":1,"lessons":{},"cards":{},"history":[],"streak":0,"dailyGoal":10,"lastActive":"2026-11-10T12:00:00.000Z"}'::jsonb
    )$$,
  '42501',
  null,
  'RPC rejects an expected user that is not the authenticated user'
);

select results_eq(
  $$select applied, progress is null, current_sync_id is null
      from public.save_user_progress(
        '22222222-2222-2222-2222-222222222222',
        gen_random_uuid(),
        '{"v":1,"lessons":{},"cards":{},"history":[],"streak":0,"dailyGoal":10,"lastActive":"2026-11-10T12:00:00.000Z"}'::jsonb
      )$$,
  $$values (false, true, true)$$,
  'a missing row with a token returns a conflict without inventing a document'
);

select results_eq(
  $$select applied
      from public.save_user_progress(
        '22222222-2222-2222-2222-222222222222',
        null,
        '{"v":1,"lessons":{},"cards":{},"history":[],"streak":0,"dailyGoal":10,"lastActive":"2026-11-10T12:00:00.000Z"}'::jsonb
      )$$,
  $$values (true)$$,
  'the other user can insert their own first row'
);

select results_eq(
  $$select applied, progress ->> 'streak'
      from public.save_user_progress(
        '22222222-2222-2222-2222-222222222222',
        null,
        '{"v":1,"lessons":{},"cards":{},"history":[],"streak":7,"dailyGoal":10,"lastActive":"2026-11-10T12:01:00.000Z"}'::jsonb
      )$$,
  $$values (false, '0')$$,
  'a second null-token insert conflicts instead of overwriting'
);

select is(
  (select progress ->> 'streak' from public.user_progress
    where user_id = '22222222-2222-2222-2222-222222222222'),
  '0',
  'the conflicting null-token insert did not mutate the row'
);

set local request.jwt.claim.sub = '11111111-1111-1111-1111-111111111111';

select is(
  (select progress ->> 'streak' from public.user_progress
    where user_id = '11111111-1111-1111-1111-111111111111'),
  '3',
  'the owner row is intact after cross-user attempts'
);

select * from finish();
rollback;
